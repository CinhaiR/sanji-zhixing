ALL_ROUTES: List[Dict[str, Any]] = RED_ROUTES + CLASSIC_ROUTES

# 展示顺序：红色线路在前（官方策展），其后为经典主题
CATEGORY_ORDER = ["红色记忆", "古建营造", "博物馆藏", "晋商文化", "佛教艺术", "山川自然"]


def list_routes(category: Optional[str] = None) -> List[Dict[str, Any]]:
    """返回全部线路；可按主题筛选。"""
    routes = ALL_ROUTES
    if category and category != "全部":
        routes = [r for r in routes if r.get("category") == category]
    return list(routes)


def get_route(route_id: str) -> Optional[Dict[str, Any]]:
    for r in ALL_ROUTES:
        if r["id"] == route_id:
            return dict(r)
    return None


def categories() -> List[str]:
    """返回出现过的主题分类（按 CATEGORY_ORDER 排序，未知的排最后）。"""
    seen = {r.get("category", "") for r in ALL_ROUTES}
    ordered = [c for c in CATEGORY_ORDER if c in seen]
    ordered += sorted(c for c in seen if c and c not in CATEGORY_ORDER)
    return ["全部"] + ordered


def validate_routes(city_names: Optional[set] = None) -> List[str]:
    """自检线路数据，返回问题列表（供启动期与测试使用）。

    关键校验：`days >= len(cities)` —— 与行程生成的合理性规则保持一致，
    否则「一键套用」会被后端直接拒绝，用户体验断裂。
    """
    problems: List[str] = []
    ids = set()
    for r in ALL_ROUTES:
        rid = r.get("id", "")
        if not rid:
            problems.append(f"线路缺 id：{r.get('name')}")
        elif rid in ids:
            problems.append(f"线路 id 重复：{rid}")
        ids.add(rid)

        for key in ("name", "route", "tagline", "why", "category"):
            if not str(r.get(key) or "").strip():
                problems.append(f"线路 {rid} 缺字段 {key}")

        cities = r.get("cities") or []
        days = int(r.get("days") or 0)
        if not cities:
            problems.append(f"线路 {rid} 未指定 cities")
        if days and cities and days < len(cities):
            problems.append(
                f"线路 {rid} 天数不足：{days} 日 < {len(cities)} 处府邑（会被行程生成拒绝）"
            )
        if city_names is not None:
            unknown = [c for c in cities if c not in city_names]
            if unknown:
                problems.append(f"线路 {rid} 含未知府邑：{unknown}")
    return problems
